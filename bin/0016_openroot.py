def ld():
    if not S.exists(): return {}
    return json.loads(S.read_text())

def sv(d):
    d["meta"]=d.get("meta",{})
    d["meta"]["updated"]=datetime.datetime.now().isoformat()
    S.parent.mkdir(parents=True,exist_ok=True)
    S.write_text(json.dumps(d,indent=2))

def gid(pfx,items):
    ns=[int(i["id"].split("-")[1]) for i in items if i.get("id","").startswith(pfx)]
    return f"{pfx}-{max(ns)+1:03d}" if ns else f"{pfx}-001"

def run(query):
    kw=set(query.lower().replace("?","").replace(".","").split())
    ax=[]
    for a in A:
        r=sum(k in a["statement"].lower() for k in kw)+sum(any(k in t for k in kw) for t in a.get("tags",[]))
        if r: ax.append(dict(a,relevance=r))
    ax.sort(key=lambda x:x["relevance"],reverse=True)
    aids=[a["id"] for a in ax[:5]]
    posts=[p for p in P if any(i in p.get("from_axioms",[]) for i in aids)]
    if not posts and ax: posts=[{"id":"PO-S","statement":f"Derived: {ax[0]['statement']} applies here.","synthetic":True}]
    conf=min(1.0,0.3+0.15*len(ax))
    eff=round(C["Cr"]["v"]*conf,4)
    L=["# OpenRoot Deep Dive Report",f"**Query:** {query}",f"**Generated:** {datetime.datetime.now().isoformat()}","---"]
    L.append(f"\n## Step 1: Define Axioms\nFound {len(A)} axioms; {len(ax)} relevant:")
    for a in ax[:5]: L.append(f"- **{a['id']}**: {a['statement']} _(rel:{a['relevance']})_")
    L.append("\n## Step 2: Form Postulates")
    for p in posts: L.append(f"- **{p['id']}**: {p['statement']}")
    L.append("\n## Step 3: Permaculture Principles Applied")
    for k,v in PM.items(): L.append(f"- **{k.title()}** — {v}")
    L.append("\n## Step 4: Update Axioms (refined)")
    for a in ax[:3]: L.append(f"- {a['id']}: refined through observation lens")
    L.append(f"\n## Step 5: Reasoning Chain\n**Confidence:** {conf:.0%}")
    axt="; ".join(a["statement"] for a in ax[:3])
    pot="; ".join(p["statement"] for p in posts[:2])
    L.append(f"```\nGiven [{axt}] and [{pot}], the query is resolved at the intersection of governing principles.\n```")
    L.append(f"\n## Step 6: Energy/Learning Efficiency\n**Efficiency:** {eff}\n**Interpretation:** Optimal ratio ~{C['Cr']['v']:.3f}; present 61.8% core, 38.2% context.")
    L.append("\n## Step 7: Auto-Variables")
    for t in [t for t in kw if len(t)>3 and t.isalpha()][:8]: L.append(f"- {t}: unit=?(unmapped)")
    L.append("\n## Step 8: Nomenclature Reference\n| Symbol | Name | Unit | Dimension |\n|---|---|---|---|")
    for s,i in N.items(): L.append(f"| {s} | {i['n']} | {i['u']} | {i['d']} |")
    L.append("\n---\n*Generated by openroot — Euclidean Calc Engine*")
    return "\n".join(L),conf,eff

def main():
    p=argparse.ArgumentParser(prog="openroot")
    sub=p.add_subparsers(dest="cmd")
    i=sub.add_parser("init");i.add_argument("--force",action="store_true")
    sub.add_parser("status")
    ax=sub.add_parser("axiom");sax=ax.add_subparsers(dest="sc");aa=sax.add_parser("add");aa.add_argument("statement");aa.add_argument("--tag",default="");al=sax.add_parser("list")
    dd=sub.add_parser("deepdive");sdd=dd.add_subparsers(dest="sc");r=sdd.add_parser("report");r.add_argument("query");r.add_argument("--output",default=None)
    a=args=p.parse_args()
    if args.cmd=="init":
        d={} if args.force else ld()
        d.setdefault("meta",{}).update({"version":"0.1.0","created":datetime.datetime.now().isoformat()})
        if not d.get("axioms"): d["axioms"]=list(A)
        if not d.get("postulates"): d["postulates"]=list(P)
        if not d.get("coefficients"): d["coefficients"]=C
        d.setdefault("variables",[]);d.setdefault("reports",[])
        sv(d);print(f"[openroot] Init @ {S}\n  Axioms:{len(d['axioms'])} Posts:{len(d['postulates'])} Coefs:{len(d['coefficients'])}")
    elif args.cmd=="status":
        d=ld();print(f"[openroot] {S}\n  Ver:{d.get('meta',{}).get('version','?')} Ax:{len(d.get('axioms',[]))} Po:{len(d.get('postulates',[]))} Co:{len(d.get('coefficients',{}))} Va:{len(d.get('variables',[]))} Re:{len(d.get('reports',[]))}") if d else print("[openroot] Not initialized. Run: openroot init")
    elif args.cmd=="axiom":
        d=ld()
        if args.sc=="add":
            aid=gid("AX",d.get("axioms",[]));tags=args.tag.split(",") if args.tag else [];d.setdefault("axioms",[]).append({"id":aid,"statement":args.statement,"tags":tags});sv(d);print(f"[openroot] Added {aid}: {args.statement}")
        elif args.sc=="list":
            for a in d.get("axioms",[]):print(f"  {a['id']}: {a['statement']}  [{','.join(a.get('tags',[]))}]") if d.get("axioms") else print("none")
    elif args.cmd=="deepdive" and args.sc=="report":
        d=ld()
        if not d.get("axioms"):print("[openroot] Run init first");return
        md,conf,eff=run(args.query);d.setdefault("reports",[]).append({"query":args.query,"time":datetime.datetime.now().isoformat(),"conf":conf,"eff":eff});sv(d)
        if args.output:Path(args.output).write_text(md);print(f"[openroot] Wrote {args.output}")
        else:print(md)

if __name__=="__main__":main()
