"""doc_compile.py — Cross-device document compiler (A15/Termux + OptiPlex)
Scans ALL new/modified .md/.txt docs in past 24h for the detected machine,
compiles into one timestamped doc in ~/openroot/context_bridge/.
Usage: python3 doc_compile.py [--hours 48] [--dry-run]
"""

import os
import sys
import json
import socket
import argparse
from datetime import datetime
from pathlib import Path
from typing import List, Tuple

DEFAULT_HOURS = 24
MAX_DOC_BYTES = 512 * 1024
SKIP_DIRS = {
    '.git', '.cache', '.config', '.local', '.npm', '.cargo', '.rustup',
    'node_modules', 'venv', '__pycache__', '.Trash', '.thumbnails',
    'Android', 'LOST.DIR', 'DCIM/Camera', 'Movies', 'Music', 'Podcasts',
    'Audiobooks', 'Download', 'Pictures', 'WhatsApp', 'Telegram',
}
EXTENSIONS = ('.md', '.txt')


def detect_machine() -> str:
    host = socket.gethostname().lower()
    if 'optiplex' in host:
        return 'optiplex'
    if 'TERMUX_VERSION' in os.environ or os.path.exists('/data/data/com.termux'):
        return 'termux'
    if str(Path.home()).startswith('/data/data/com.termux'):
        return 'termux'
    return 'unknown'


def get_scan_roots(machine: str) -> List[str]:
    roots = []
    if machine == 'optiplex':
        roots = [str(Path.home()), '/mnt/sdb1']
    elif machine == 'termux':
        home = str(Path.home())
        roots = [home, os.path.join(home, 'storage/shared'), '/storage/emulated/0']
    else:
        roots = [str(Path.home())]
    seen, valid = set(), []
    for r in roots:
        rp = os.path.realpath(r)
        if rp not in seen and os.path.isdir(rp):
            seen.add(rp)
            valid.append(r)
    return valid


def scan_documents(roots: List[str], hours: int) -> List[Tuple[Path, float]]:
    cutoff = datetime.now().timestamp() - (hours * 3600)
    docs = []
    for root_dir in roots:
        print(f"[SCAN] {root_dir}", file=sys.stderr)
        for root, dirs, files in os.walk(root_dir, followlinks=False):
            dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
            for filename in files:
                if not filename.lower().endswith(EXTENSIONS):
                    continue
                fp = Path(root) / filename
                try:
                    stat = fp.stat()
                    if stat.st_size > MAX_DOC_BYTES:
                        continue
                    if stat.st_mtime >= cutoff:
                        docs.append((fp, stat.st_mtime))
                except (PermissionError, FileNotFoundError, OSError):
                    continue
    seen, unique = set(), []
    for p, m in docs:
        rp = str(p.resolve())
        if rp not in seen:
            seen.add(rp)
            unique.append((p, m))
    return sorted(unique, key=lambda x: x[1])


def safe_read(filepath: Path) -> str:
    try:
        with open(filepath, 'rb') as f:
            raw = f.read(MAX_DOC_BYTES)
        try:
            return raw.decode('utf-8')
        except UnicodeDecodeError:
            return raw.decode('latin-1', errors='replace')
    except Exception as e:
        return f"[unreadable: {e}]"


def output_path(machine: str) -> Path:
    ts = datetime.now().strftime('%Y%m%d_%H%M%S')
    return Path.home() / 'openroot' / 'context_bridge' / f"doc_compile_{machine}_{ts}.md"


def compile_docs(docs: List[Tuple[Path, float]], machine: str, hours: int) -> str:
    header = [
        "# Daily Document Compilation", "",
        f"**Machine:** {machine} ({socket.gethostname()})",
        f"**Generated:** {datetime.now().isoformat()}",
        f"**Window:** past {hours} hours",
        f"**Documents:** {len(docs)}", "", "---", "",
    ]
    sections, total_words = [], 0
    for fp, mtime in docs:
        content = safe_read(fp)
        total_words += len(content.split())
        mod = datetime.fromtimestamp(mtime).strftime('%Y-%m-%d %H:%M:%S')
        sections.extend([
            f"## {fp.name}", "",
            f"- **Path:** `{fp}`",
            f"- **Modified:** {mod}",
            f"- **Size:** {fp.stat().st_size} bytes", "",
            content.strip(), "", '─' * 72, "",
        ])
    summary = [
        "## Compilation Summary", "",
        "| Metric | Value |", "|--------|-------|",
        f"| Documents | {len(docs)} |",
        f"| Total words | {total_words} |",
        f"| Window | {hours}h |",
        f"| Machine | {machine} |", "",
        "*Generated by doc_compile.py — [exit=0]*",
    ]
    return "\n".join(header + sections + summary)


def main():
    ap = argparse.ArgumentParser(description='Cross-device 24h document compiler')
    ap.add_argument('--hours', type=int, default=DEFAULT_HOURS)
    ap.add_argument('--dry-run', action='store_true')
    args = ap.parse_args()

    machine = detect_machine()
    roots = get_scan_roots(machine)
    print(f"[INFO] Machine detected: {machine}", file=sys.stderr)
    if not roots:
        print("[ERROR] No accessible scan roots found.", file=sys.stderr)
        sys.exit(1)

    docs = scan_documents(roots, args.hours)
    print(f"[INFO] New/modified documents in past {args.hours}h: {len(docs)}", file=sys.stderr)
    for fp, mtime in docs:
        mod = datetime.fromtimestamp(mtime).strftime('%H:%M:%S')
        print(f"  [FOUND] {fp}  (modified {mod})", file=sys.stderr)

    if not docs:
        print("[WARN] Nothing to compile. Try --hours 48.", file=sys.stderr)
        sys.exit(0)

    compiled = compile_docs(docs, machine, args.hours)
    out = output_path(machine)

    if args.dry_run:
        print(f"[DRY-RUN] Would write: {out} ({len(compiled)} bytes)", file=sys.stderr)
        print(compiled[:3000] + ("\n...[truncated]" if len(compiled) > 3000 else ""))
        sys.exit(0)

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(compiled, encoding='utf-8')
    print(f"[BANKED] {out} ({len(compiled)} bytes)", file=sys.stderr)
    sys.exit(0)


if __name__ == "__main__":
    main()
