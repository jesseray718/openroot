import os
import sys
import json
import hashlib
import zipfile
from pathlib import Path
from datetime import datetime, timezone
from collections import defaultdict
import shutil

BASE_DIR = Path.home() / "agapenet"
COMPRESSED_DIR = BASE_DIR / "_compressed_bundle"

def get_utc_now():
    """Return timezone-aware UTC timestamp."""
    return datetime.now(timezone.utc).isoformat()

def sha256_file(filepath):
    """Compute SHA-256 hash of file content."""
    h = hashlib.sha256()
    try:
        with open(filepath, 'rb') as f:
            for chunk in iter(lambda: f.read(8192), b''):
                h.update(chunk)
    except (IOError, OSError):
        return None
    return h.hexdigest()

def scan_agapenet(root_dir):
    """Walk directory tree and collect file metadata."""
    files = []
    root_path = Path(root_dir)
    for path in root_path.rglob('*'):
        if path.is_file() and not path.name.startswith('.'):
            files.append({
                "path": str(path.relative_to(root_path)),
                "abs_path": str(path),
                "size": path.stat().st_size if path.exists() else 0
            })
    return sorted(files, key=lambda x: x["path"])

def compute_hashes(files):
    """Hash all files and group duplicates by SHA-256."""
    hashes = {}
    for f in files:
        h = sha256_file(f["abs_path"])
        f["hash"] = h
        if h:
            hashes.setdefault(h, []).append(f["path"])
    return hashes

def generate_manifest(files, total_size):
    """Build manifest dictionary."""
    return {
        "version": "2.0",
        "timestamp": get_utc_now(),
        "root": str(BASE_DIR),
        "file_count": len(files),
        "total_raw_bytes": total_size,
        "files": [
            {
                "path": f["path"],
                "hash": f.get("hash", "N/A"),
                "size": f["size"]
            }
            for f in files
        ]
    }

def create_zip_bundle(files, zip_path):
    """Compress files into zip archive."""
    with zipfile.ZipFile(zip_path, 'w', zipfile.ZIP_DEFLATED) as zf:
        for f in files:
            try:
                zf.write(f["abs_path"], f["path"])
            except (IOError, OSError) as e:
                print(f"[WARN] Skip {f['path']}: {e}")
    return Path(zip_path).stat().st_size

def dedupe_stats(hashes):
    """Calculate duplicate waste."""
    dup_groups = {h: paths for h, paths in hashes.items() if len(paths) > 1}
    waste = sum(
        sum(Path(BASE_DIR / p).stat().st_size for p in paths[1:])
        for paths in dup_groups.values()
    )
    return dup_groups, waste

def generate_report(raw_size, compressed_size, dup_groups, waste):
    """Write markdown summary report."""
    reduction_pct = ((raw_size - compressed_size) / raw_size * 100) if raw_size > 0 else 0
    num_unique = len(set(h for h, paths in dup_groups.items()))
    
    report_lines = [
        "# AGAPE_NET :: SUMMARY_REPORT",
        "**Generated:** " + get_utc_now(),
        "",
        "## Metrics",
        "- Total Unique Hashes: {}".format(num_unique),
        "- Raw Size: {:.1f} KB".format(raw_size/1024),
        "- Compressed: {:.1f} KB".format(compressed_size/1024),
        "- Compression Gain: {:.1f}%".format(reduction_pct),
        "- Deduplicated Waste: {:.1f} KB".format(waste/1024),
        "",
        "## Duplicate Groups ({})".format(len(dup_groups)),
    ]
    
    for h, paths in list(dup_groups.items())[:10]:
        report_lines.append("- `{}...` -> {} copies".format(h[:16], len(paths)))
    
    report_lines.extend(["", "---", "*Generated by AGAPE_NET Core Engine v2*"])
    
    report = "\n".join(report_lines)
    report_path = COMPRESSED_DIR / "SUMMARY_REPORT.md"
    report_path.write_text(report)

def initialize_structure():
    """Create required directories."""
    COMPRESSED_DIR.mkdir(parents=True, exist_ok=True)

def run_core_engine():
    """Execute full pipeline: init → scan → hash → dedupe → compress → report."""
    print("=" * 60)
    print("  AGAPE_NET :: CORE_ENGINE_v2")
    print("  Operator: Jesse Ray (OpenRoot)")
    print("  Maximize output per unit input per unit time")
    print("=" * 60)
    
    initialize_structure()
    
    # Scan
    print("\n[SCAN] Walking", BASE_DIR)
    start_time = datetime.now(timezone.utc)
    files = scan_agapenet(BASE_DIR)
    total_kb = sum(f['size'] for f in files)/1024
    print("[SCAN] Found {} files, total {:.1f}KB".format(len(files), total_kb))
    
    # Hash & dedupe
    print("[DEDUP] Hashing files...")
    hashes = compute_hashes(files)
    dup_groups, waste = dedupe_stats(hashes)
    dup_count = len([g for g in dup_groups.values() if len(g) > 1])
    print("[DEDUP] {} duplicate groups, ~{:.1f}B wasted".format(dup_count, waste))
    
    # Generate manifest
    total_raw = sum(f["size"] for f in files)
    manifest = generate_manifest(files, total_raw)
    manifest_path = COMPRESSED_DIR / "MANIFEST.json"
    manifest_path.write_text(json.dumps(manifest, indent=2))
    print("[MANIFEST] Written to {}".format(manifest_path))
    
    # Create zip bundle
    zip_path = COMPRESSED_DIR / "agapenet_bundle.zip"
    print("[ZIP] Compressing files...")
    compressed_size = create_zip_bundle(files, zip_path)
    print("[ZIP] Done: {} archived, freed {:.1f}KB (dupes)".format(len(files), waste/1024))
    
    # Generate report
    print("[REPORT] Writing summary...")
    generate_report(total_raw, compressed_size, dup_groups, waste)
    
    end_time = datetime.now(timezone.utc)
    elapsed = (end_time - start_time).total_seconds()
    
    # Final summary
    print("\n" + "=" * 60)
    print("  COMPLETE — {:.1f}s".format(elapsed))
    print("  Bundle:    {}".format(zip_path))
    print("  Manifest:  {}".format(manifest_path))
    print("  Report:    {}".format(COMPRESSED_DIR / "SUMMARY_REPORT.md"))
    print("  Raw:       {:.1f}KB".format(total_raw/1024))
    print("  Compressed: {:.1f}KB".format(compressed_size/1024))
    print("  Freed (dupes): {:.1f}KB".format(waste/1024))
    print("=" * 60)

if __name__ == "__main__":
    try:
        run_core_engine()
    except KeyboardInterrupt:
        print("\n[ABORT] Interrupted by operator")
        sys.exit(1)
    except Exception as e:
        print("\n[FATAL] {}: {}".format(type(e).__name__, e))
        sys.exit(1)
